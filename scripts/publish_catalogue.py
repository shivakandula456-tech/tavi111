#!/usr/bin/env python3
"""Generate GitHub Pages seed files from an Admin-exported catalogue JSON."""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "data" / "catalogue-publish.json"
PRODUCTS = ROOT / "data" / "products.js"
CATEGORIES = ROOT / "data" / "categories.js"
SETTINGS = ROOT / "data" / "settings.js"
STORAGE = ROOT / "assets" / "js" / "storage.js"

def fail(message):
    print(f"ERROR: {message}", file=sys.stderr)
    raise SystemExit(1)

if not SOURCE.exists():
    fail("data/catalogue-publish.json is missing. Export it from Admin > Settings and add it to the repository.")

try:
    payload = json.loads(SOURCE.read_text(encoding="utf-8"))
except Exception as exc:
    fail(f"Catalogue file is not valid JSON: {exc}")

if payload.get("format") != "tavish-publish-catalogue" or payload.get("version") != 1:
    fail("Unsupported catalogue file. Use Admin > Settings > Export catalogue for GitHub publishing.")
products = payload.get("products")
categories = payload.get("categories")
settings = payload.get("settings")
if not isinstance(products, list) or not products:
    fail("Catalogue must contain a non-empty products array.")
if not isinstance(categories, list):
    fail("Catalogue must contain a categories array.")
if not isinstance(settings, dict):
    fail("Catalogue must contain a settings object.")

seen_skus, seen_slugs = set(), set()
for i, product in enumerate(products, 1):
    if not isinstance(product, dict):
        fail(f"Product #{i} is not an object.")
    sku = str(product.get("sku", "")).strip().lower()
    slug = str(product.get("slug", "")).strip().lower()
    if not sku or not slug:
        fail(f"Product #{i} is missing SKU or slug.")
    if sku in seen_skus:
        fail(f"Duplicate SKU: {product.get('sku')}")
    if slug in seen_slugs:
        fail(f"Duplicate product slug: {product.get('slug')}")
    seen_skus.add(sku); seen_slugs.add(slug)
    if not isinstance(product.get("images", []), list):
        fail(f"Product {product.get('sku')} has an invalid images list.")
    for field in ("primaryImage", "image"):
        value = product.get(field)
        if value is not None and not isinstance(value, str):
            fail(f"Product {product.get('sku')} has invalid {field}.")

def js(value):
    # JSON is valid JavaScript for these data-only seed files.
    return json.dumps(value, ensure_ascii=False, indent=2).replace("</", "<\\/")

PRODUCTS.write_text("/* Generated by GitHub Actions from the approved Admin catalogue export. */\nwindow.TAVISH_SEED_PRODUCTS = " + js(products) + ";\n", encoding="utf-8")
CATEGORIES.write_text("/* Generated by GitHub Actions from the approved Admin catalogue export. */\nwindow.TAVISH_SEED_CATEGORIES = " + js(categories) + ";\n", encoding="utf-8")
SETTINGS.write_text("/* Generated by GitHub Actions from the approved Admin catalogue export. */\nwindow.TAVISH_SEED_SETTINGS = " + js(settings) + ";\n", encoding="utf-8")

storage = STORAGE.read_text(encoding="utf-8")
match = re.search(r"var SEED_VERSION = (\d+);", storage)
if not match:
    fail("Could not find SEED_VERSION in assets/js/storage.js.")
old = int(match.group(1))
storage = storage[:match.start(1)] + str(old + 1) + storage[match.end(1):]
STORAGE.write_text(storage, encoding="utf-8")

# Remove the submitted staging file from the published repository after processing.
SOURCE.unlink()
print(f"Validated and generated {len(products)} products and {len(categories)} categories.")
print(f"Seed version bumped from {old} to {old + 1}; staging JSON removed.")
